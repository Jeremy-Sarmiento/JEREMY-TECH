-- Jeremy Tech: tabla de banners gestionados desde base de datos
BEGIN;

CREATE TABLE IF NOT EXISTS banners (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  titulo varchar(120) NOT NULL,
  subtitulo varchar(255) NOT NULL DEFAULT '',
  enlace varchar(255) NOT NULL DEFAULT '',
  orden integer NOT NULL DEFAULT 0,
  activo smallint NOT NULL DEFAULT 1,
  mime varchar(60) NOT NULL,
  datos bytea NOT NULL,
  actualizado_en timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);

-- El backend PHP usa la conexión privada; la API pública de Supabase no accede.
ALTER TABLE banners ENABLE ROW LEVEL SECURITY;

COMMIT;
